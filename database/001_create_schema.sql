CREATE TABLE users(
    id BIGSERIAL PRIMARY KEY,
    email VARCHAR(120) NOT NULL,
    pw VARCHAR(10) NOT NULL,
    rol VARCHAR(100) NOT NULL,

    CONSTRAINT ckk_rol 
    CHECK (rol IN (
        'ESTUDIANTE', 
        'PROFESOR', 
        'PERSONAL ADMINISTRATIVO', 
        'BRIGADISTA', 
        'COORDINADOR DE EMERGENCIAS',
        'ORGANIZADOR DE SIMULACROS',
        'AUDITOR'
        ))
);
